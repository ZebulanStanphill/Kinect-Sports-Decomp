static __forceinline __vector4 Length3(__vector4 v)
{
    __vector4 d, h, rsq, rt, mask, rcp, zero, result;

    d = __vmsum3fp(v, v);
    h = __vspltisw(1);
    zero = __vspltisw(0);
    h = __vcfsx(h, 1);
    rsq = __vrsqrtefp(d);
    rt = __vmulfp(d, h);
    mask = __vcmpeqfp(d, zero);
    rcp = __vmulfp(rsq, rsq);
    h = __vnmsubfp(rt, rcp, h);
    rsq = __vmaddfp(rsq, h, rsq);
    result = __vmulfp(d, rsq);
    return __vsel(result, d, mask);
}

static __forceinline __vector4 Normalize3(__vector4 v)
{
    __vector4 d, h, rsq, rt, mask, rcp, zero, result;

    d = __vmsum3fp(v, v);
    h = __vspltisw(1);
    zero = __vspltisw(0);
    h = __vcfsx(h, 1);
    rsq = __vrsqrtefp(d);
    rt = __vmulfp(d, h);
    mask = __vcmpeqfp(d, zero);
    rcp = __vmulfp(rsq, rsq);
    h = __vnmsubfp(rt, rcp, h);
    rsq = __vmaddfp(rsq, h, rsq);
    result = __vmulfp(v, rsq);
    return __vsel(result, d, mask);
}

static __forceinline __vector4 Replicate(float value)
{
    return __vspltw(__lvlx(&value, 0), 0);
}

/* Keeps point within [0.85, 1.15] * distance of anchor along the anchor-to-point direction:
   writes the clamped position and returns 1 when it had to move it. */
int fn_82A03570(float distance, __vector4 *out, __vector4 point, __vector4 anchor, __vector4 base)
{
    __vector4 delta, length, dir;

    delta = __vsubfp(point, anchor);
    length = Length3(delta);
    dir = Normalize3(delta);
    if (length.vector4_f32[0] < distance * 0.85f) {
        *out = __vmaddfp(dir, Replicate(distance * 0.85f), base);
        return 1;
    }
    if (length.vector4_f32[0] > distance * 1.15f) {
        *out = __vmaddfp(dir, Replicate(distance * 1.15f), base);
        return 1;
    }
    return 0;
}
